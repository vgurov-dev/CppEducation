static int failed = 0;

void check(bool ok, const char* name) {
    std::cout << (ok ? "  OK   " : "  FAIL ") << name << '\n';
    if (!ok) ++failed;
}

bool equal(const int* a, const int* b, std::size_t n) {
    if (a == nullptr || b == nullptr) return false;
    for (std::size_t i = 0; i < n; ++i)
        if (a[i] != b[i]) return false;
    return true;
}

